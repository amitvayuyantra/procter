"""One-off generator for the face-mesh drawing data (run from the backend folder: python tools/make_mesh.py).

Picks ~150 of MediaPipe's 478 face points and joins them into triangles using a real front-facing photo
as the template. Writes app/mesh.py (for the server) and ../frontend/lib/faceMesh.ts (for the browser).
"""
from pathlib import Path

import cv2
import mediapipe as mp
import numpy as np
from mediapipe.tasks import python as P
from mediapipe.tasks.python import vision

ROOT = Path(__file__).resolve().parent.parent
GROUPS = {
    "oval": [10, 338, 297, 332, 284, 251, 389, 356, 454, 323, 361, 288, 397, 365, 379, 378, 400, 377, 152, 148, 176,
             149, 150, 136, 172, 58, 132, 93, 234, 127, 162, 21, 54, 103, 67, 109],
    "eyeA": [33, 7, 163, 144, 145, 153, 154, 155, 133, 173, 157, 158, 159, 160, 161, 246],  # on the left of a camera picture
    "eyeB": [263, 249, 390, 373, 374, 380, 381, 382, 362, 398, 384, 385, 386, 387, 388, 466],
    "lips": [61, 146, 91, 181, 84, 17, 314, 405, 321, 375, 291, 409, 270, 269, 267, 0, 37, 39, 40, 185],
    "browA": [70, 63, 105, 66, 107], "browB": [336, 296, 334, 293, 300],
    "nose": [168, 6, 197, 195, 5, 4, 1],
}
FILL = [46, 53, 52, 65, 55, 276, 283, 282, 295, 285, 19, 94, 2, 98, 97, 326, 327, 129, 358, 49, 279, 9, 8, 151, 108,
        337, 50, 101, 118, 117, 111, 280, 330, 347, 346, 340, 205, 36, 425, 266, 187, 123, 411, 352, 147, 213, 192,
        376, 433, 416, 138, 135, 215, 364, 367, 175, 199, 200, 18, 83, 313, 182, 406, 71, 301, 68, 298]
IRIS = {"irisA": 468, "irisB": 473}  # centres of the two irises

points: list[int] = []
for ids in [*GROUPS.values(), FILL, list(IRIS.values())]:
    for i in ids:
        if i not in points:
            points.append(i)
pos = {i: n for n, i in enumerate(points)}

photo = cv2.imread(str(ROOT / "tests/data/astronaut.jpg"))
h, w = photo.shape[:2]
lm = vision.FaceLandmarker.create_from_options(vision.FaceLandmarkerOptions(
    base_options=P.BaseOptions(model_asset_buffer=(ROOT / "models/face_landmarker.task").read_bytes()), num_faces=1))
out = lm.detect(mp.Image(image_format=mp.ImageFormat.SRGB, data=np.ascontiguousarray(cv2.cvtColor(photo, cv2.COLOR_BGR2RGB))))
L = out.face_landmarks[0]
xy = np.array([[L[i].x * w, L[i].y * h] for i in points], np.float32)

# sanity: iris 468 must sit inside eyeA (otherwise left/right are swapped)
ea = xy[[pos[i] for i in GROUPS["eyeA"]]]
assert ea[:, 0].min() < xy[pos[468]][0] < ea[:, 0].max(), "iris/eye sides do not match"

sub = cv2.Subdiv2D((0, 0, w, h))
for p in xy:
    sub.insert((float(p[0]), float(p[1])))
poly = lambda g: xy[[pos[i] for i in GROUPS[g]]].astype(np.float32).reshape(-1, 1, 2)  # noqa: E731
face_w = xy[pos[454]][0] - xy[pos[234]][0]
tris = []
for t in sub.getTriangleList():
    pts = t.reshape(3, 2)
    idx = [int(np.argmin(np.linalg.norm(xy - p, axis=1))) for p in pts]
    if len(set(idx)) < 3 or np.linalg.norm(xy[idx] - pts, axis=1).max() > 1.0:
        continue  # a triangle touching the outer frame, not our points
    c = tuple(float(v) for v in xy[idx].mean(axis=0))
    inside = cv2.pointPolygonTest(poly("oval"), c, False) > 0
    in_hole = any(cv2.pointPolygonTest(poly(g), c, False) > 0 for g in ("eyeA", "eyeB", "lips"))
    long_edge = max(np.linalg.norm(xy[idx[a]] - xy[idx[b]]) for a, b in ((0, 1), (1, 2), (0, 2))) > 0.34 * face_w
    if inside and not in_hole and not long_edge:
        tris.append(sorted(idx))
tris = sorted(set(map(tuple, tris)))

(ROOT / "app/mesh.py").write_text(
    '"""Which face points are sent to the browser to draw the mesh. Generated by tools/make_mesh.py."""\n\n'
    f"MESH_POINTS = {points}\n")
ts = ["// Generated by backend/tools/make_mesh.py. Do not edit by hand.",
      f"export const TRIANGLES: number[] = {[v for t in tris for v in t]};"]
for name, ids in GROUPS.items():
    ts.append(f"export const {name.upper()}: number[] = {[pos[i] for i in ids]};")
ts.append(f"export const IRIS_A = {pos[468]};\nexport const IRIS_B = {pos[473]};")
ts.append(f"export const POINT_COUNT = {len(points)};")
(ROOT.parent / "frontend/lib/faceMesh.ts").write_text("\n".join(ts) + "\n")
print(f"{len(points)} points, {len(tris)} triangles")
